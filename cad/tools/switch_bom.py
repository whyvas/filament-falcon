"""Write docs/mechanical/switch_bom.md: bill of switches/buttons/LEDs per panel (from layouts.py)."""
import os, collections
import layouts as L

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
PART = {
    "tog6": "Mini toggle switch SPST/SPDT, 6 mm (1/4\") bushing (MTS-102 style)",
    "tog6g": "Mini toggle 6 mm + printed missile guard (toggle_guard.3mf)",
    "tog12": "Heavy toggle 12 mm bushing, DPDT (ON)-OFF-(ON) momentary, >= 15 A @ 12 V DC",
    "btn12": "12 mm momentary push button",
    "btn16": "16 mm momentary push button (metal/illuminated ok)",
    "arc19": "19 mm push button, 19 mm panel hole (metal anti-vandal or mini arcade)",
    "arc22": "22 mm push button, 22 mm panel hole (industrial 22 mm or mini arcade)",
    "estop22": "22 mm mushroom E-stop, NC, latching, twist-release",
    "led5": "5 mm LED + bezel/holder (or a WS2812B 5 mm through-hole)",
    "ec11": "EC11 rotary encoder with push switch + knob",
    "key19": "19 mm key switch, 2 position, key removable in OFF only",
    "pot7": "16 mm potentiometer, 10 k linear (7 mm bushing)",
    "slot": "lever slot (printed mechanism below the panel)",
}

def main():
    out = ["# Bill of switches, buttons and indicators per panel", "",
           "Generated by `cad/tools/switch_bom.py` from `cad/tools/layouts.py` - do not edit by hand.", ""]
    total = collections.Counter()
    for p in L.PANELS:
        c = collections.Counter(k["kind"] for k in p.controls)
        total.update(c)
        out += [f"## {p.id} ({p.w} x {p.h} mm) - {p.title}; {p.where}", "", "| Qty | Part | Used for |", "|---|---|---|"]
        for kind, n in sorted(c.items()):
            uses = ", ".join(sorted({(k['label'] or '').strip() for k in p.controls if k['kind'] == kind and k['label']}))
            out.append(f"| {n} | {PART.get(kind, kind)} | {uses} |")
        out.append("")
    out += ["## Totals (all panels)", "", "| Qty | Part |", "|---|---|"]
    for kind, n in sorted(total.items()):
        out.append(f"| {n} | {PART.get(kind, kind)} |")
    out += ["", "Buy ~10 % spares of the small parts. Panel thickness is 3 mm, so every nut-mounted part fits;",
            "snap-in buttons rated for 1-3 mm panels clip in directly."]
    path = os.path.join(ROOT, "docs", "mechanical", "switch_bom.md")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "w").write("\n".join(out) + "\n")
    print("wrote", path, dict(total))

if __name__ == "__main__":
    main()
