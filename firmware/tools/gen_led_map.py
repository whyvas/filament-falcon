"""Generate include/led_segments_gen.h from ../shared/led_segments.json.

Runs automatically before every PlatformIO build (extra_scripts = pre:...),
and can also be run by hand:  python3 tools/gen_led_map.py
"""
import json, os, re, pathlib

try:
    Import("env")  # noqa: F821  (PlatformIO SCons)
    PROJ = pathlib.Path(env.subst("$PROJECT_DIR"))  # noqa: F821
except NameError:
    PROJ = pathlib.Path(__file__).resolve().parents[1]

SRC = PROJ.parent / "shared" / "led_segments.json"
DST = PROJ / "include" / "led_segments_gen.h"


def generate():
    data = json.loads(SRC.read_text())
    segs = data["segments"]
    total = int(data["strip"]["total_leds"])
    lines = [
        "// AUTO-GENERATED by tools/gen_led_map.py from shared/led_segments.json.",
        "// Do not edit; edit the JSON and rebuild.",
        "#pragma once",
        "#include <stdint.h>",
        "struct LedSegment { const char *id; uint16_t start; uint16_t count; };",
    ]
    end = 0
    rows = []
    for lid, s in segs.items():
        if not re.fullmatch(r"[A-Z0-9_]+", lid):
            raise SystemExit(f"led_segments.json: bad label id {lid!r} (use A-Z 0-9 _)")
        st, ct = int(s["start"]), int(s["count"])
        end = max(end, st + ct)
        rows.append(f'  {{"{lid}", {st}, {ct}}},')
    if end > total:
        raise SystemExit(f"led_segments.json: segments reach LED {end} but total_leds={total}")
    lines.append(f"#define FF_NUM_LEDS {total}")
    lines.append(f"#define FF_NUM_SEGMENTS {len(rows)}")
    lines.append("static const LedSegment FF_LED_SEGMENTS[FF_NUM_SEGMENTS] = {")
    lines += rows
    lines.append("};")
    text = "\n".join(lines) + "\n"
    if not DST.exists() or DST.read_text() != text:
        DST.write_text(text)
        print(f"gen_led_map: wrote {DST.name} ({len(rows)} segments, {total} LEDs)")


generate()
