#!/usr/bin/env python3
"""Generate shared/input_map.json from the board config headers.

The config headers (firmware/include/config_*.h) are the single source of truth
for which switch is which HID button/axis. Run this after editing them:
    python3 firmware/tools/gen_input_map.py
"""
import json, re, pathlib

FW = pathlib.Path(__file__).resolve().parents[1]
OUT = FW.parent / "shared" / "input_map.json"
SLOTS = ["AX_X", "AX_Y", "AX_Z", "AX_RX", "AX_RY", "AX_RZ", "AX_SLIDER", "AX_DIAL"]
SLOT_NAMES = ["X", "Y", "Z", "Rx", "Ry", "Rz", "Slider", "Dial"]
KINDS = {"K_MOMENTARY": "momentary", "K_TOGGLE": "toggle", "K_ROTARY": "rotary", "K_PULSE": "pulse"}

BOARDS = [
    ("config_pilot.h", "Falcon Pilot", "0x0003", "Left seat - PILOT (rotation, main engine)"),
    ("config_ops.h", "Falcon Ops", "0x0004", "Right seat - OPS (translation, systems, payload)"),
    ("config_command.h", "Falcon Command", "0x0005",
     "Rear seat (dad) + overhead console; also HID+CDC serial for LEDs"),
]


def defines(text):
    return dict(re.findall(r"#define\s+(PIN_\w+)\s+(\d+)", text))


def src_desc(src, ref, pins):
    ref = pins.get(ref, ref)
    return {"SRC_GPIO": f"GPIO{ref} (active low)", "SRC_GPIO_HIGH": f"GPIO{ref} (active high)",
            "SRC_SR": f"74HC165 bit {ref} (chip {int(ref)//8 + 1}, input {'ABCDEFGH'[int(ref)%8]})",
            "SRC_ENC_CW": f"encoder {ref} clockwise", "SRC_ENC_CCW": f"encoder {ref} counter-clockwise"}[src]


def main():
    pins = defines((FW / "include" / "board_pins.h").read_text())
    devices, actions = {}, {}
    for fname, dev, pid, role in BOARDS:
        text = (FW / "include" / fname).read_text()
        pins_b = {**pins, **defines(text)}
        axes, buttons = {}, {}
        for m in re.finditer(r'FF_AXIS\(\s*(\w+),\s*(\w+),\s*(\w+),\s*(\w+),\s*(\d+),\s*"(\w+)"\)', text):
            pin, slot, mode, inv, dz, act = m.groups()
            idx = SLOTS.index(slot)
            axes[str(idx)] = act
            assert act not in actions, f"duplicate action {act}"
            actions[act] = {"device": dev, "axis": idx, "invert": False, "mode": mode.lower(),
                            "source": f"GPIO{pins_b.get(pin, pin)} ({SLOT_NAMES[idx]})"}
        for m in re.finditer(r'FF_ENC\(\s*(\w+),\s*(\w+),\s*(\w+),\s*(\w+),\s*(\d+),\s*"(\w*)"\)', text):
            pa, pb, rev, slot, step, act = m.groups()
            if slot == "AX_NONE":
                continue
            idx = SLOTS.index(slot)
            axes[str(idx)] = act
            assert act not in actions, f"duplicate action {act}"
            actions[act] = {"device": dev, "axis": idx, "invert": False, "mode": "unipolar",
                            "source": f"EC11 knob on GPIO{pins_b.get(pa, pa)}/GPIO{pins_b.get(pb, pb)} "
                                      f"(firmware keeps a 0..255 level, {step} per click, saved in flash)"}
        for m in re.finditer(r'FF_BTN\(\s*(\w+),\s*(\w+),\s*(\d+),\s*(\w+),\s*"(\w+)"\)', text):
            src, ref, hid, kind, act = m.groups()
            hid = int(hid)
            assert str(hid) not in buttons, f"{dev}: HID button {hid} used twice"
            assert act not in actions, f"duplicate action {act}"
            buttons[str(hid)] = act
            actions[act] = {"device": dev, "button": hid, "kind": KINDS[kind],
                            "source": src_desc(src, ref, pins_b)}
        devices[dev] = {"usb_vid": "0x1209", "usb_pid": pid, "usb_product": dev,
                        "linux_name": f"Filament Falcon {dev}", "role": role,
                        "axes": axes, "buttons": dict(sorted(buttons.items(), key=lambda kv: int(kv[0])))}
    out = {
        "_comment": "GENERATED by firmware/tools/gen_input_map.py from firmware/include/config_*.h. "
                    "Edit the headers, not this file.",
        "conventions": {
            "device": "match the joystick when its joy name CONTAINS the device key (e.g. 'Falcon Pilot'), or by "
                      "usb_vid/usb_pid (Godot: Input.get_joy_info(id) vendor_id/product_id). Linux prefixes the "
                      "manufacturer, so the evdev/SDL name is 'Filament Falcon Falcon Pilot'; Windows shows "
                      "'Falcon Pilot'. Do not use exact string equality.",
            "button": "0-based HID button index (Godot JoyButton / SDL button index). Godot raw index for "
                      "unknown devices equals this number.",
            "axis": "0-based axis index in HID report order: 0=X 1=Y 2=Z 3=Rx 4=Ry 5=Rz 6=Slider 7=Dial. "
                    "Values -1..1 (HID -32767..32767). Linux evdev: ABS_X..ABS_RZ, ABS_THROTTLE, ABS_RUDDER.",
            "bipolar": "spring-centred stick axis, 0 at rest, deadzone already applied in firmware",
            "unipolar": "lever/pot without centre: -1 = minimum (throttle idle / lights dim), +1 = maximum",
            "invert": "game-side flip; set true if a direction feels backwards (or flip in the config header)",
            "kind": "momentary = held while pressed; toggle = held while switch is ON (read the level, not "
                    "edges); rotary = exactly one of the group is held; pulse = ~35 ms press per encoder click",
        },
        "devices": devices,
        "actions": actions,
    }
    OUT.write_text(json.dumps(out, indent=2) + "\n")
    print(f"wrote {OUT}: {len(actions)} actions on {len(devices)} devices")


if __name__ == "__main__":
    main()
